/** Compact factory for a platform case that isn't a full eCourts scrape —
 * fills every required `caseDetails`/`entityInfo`/`files`/`descriptions` field
 * so the object is a valid `LegalCase` without repeating ~30 zero-value lines. */
function makeCase(input: {
  id: string;
  title: string;
  description: string;
  category: LegalCategory;
  practiceArea?: string;
  specialization?: string;
  legalService?: string;
  citizenId?: string;
  citizenName: string;
  lawyerId?: string;
  lawyerName?: string;
  status: LegalCase["status"];
  city: string;
  createdAt: string;
  updatedAt: string;
  source?: "manual" | "ecourt";
  isEmergency?: boolean;
  emergencyReason?: string;
  viaWhatsApp?: boolean;
  courtName?: string;
  caseNumber?: string;
  petitioners: string[];
  petitionerAdvocates?: string[];
  respondents: string[];
  respondentAdvocates?: string[];
  caseCategoryFacetPath?: string;
  hearings?: HistoryOfHearingSeed[];
  interimOrders?: { orderDate: string; description: string; orderUrl?: string }[];
  files?: { id: string; name: string; size: string; uploadedAt: string }[];
  timeline: LegalCase["timeline"];
  nextHearing?: string;
  lastHearing?: string;
}): LegalCase {
  const hearings = input.hearings ?? [];
  const interimOrders = input.interimOrders ?? [];
  return {
    id: input.id,
    title: input.title,
    description: input.description,
    category: input.category,
    practiceArea: input.practiceArea,
    specialization: input.specialization,
    legalService: input.legalService,
    citizenId: input.citizenId,
    citizenName: input.citizenName,
    lawyerId: input.lawyerId,
    lawyerName: input.lawyerName,
    status: input.status,
    city: input.city,
    createdAt: input.createdAt,
    updatedAt: input.updatedAt,
    source: input.source,
    isEmergency: input.isEmergency,
    emergencyReason: input.emergencyReason,
    viaWhatsApp: input.viaWhatsApp,
    timeline: input.timeline,
    caseDetails: {
      caseNumber: input.caseNumber,
      courtName: input.courtName ?? "",
      historyOfCaseHearings: hearings,
      interimOrders,
      judges: Array.from(new Set(hearings.map((h) => h.judge))),
      petitioners: input.petitioners,
      petitionerAdvocates: input.petitionerAdvocates ?? [],
      respondents: input.respondents,
      respondentAdvocates: input.respondentAdvocates ?? [],
      caseCategoryFacetPath: input.caseCategoryFacetPath,
      hasOrders: interimOrders.length > 0,
      hasJudgments: false,
      orderCount: interimOrders.length,
      interimOrderCount: interimOrders.length,
      judgmentCount: 0,
      hearingCount: hearings.length,
      iaCount: 0,
      taggedMatters: [],
      judgmentOrders: [],
    },
    entityInfo: {
      nextDateOfHearing: input.nextHearing,
      lastDateOfHearing: input.lastHearing,
      dateCreated: `${input.createdAt}T09:00:00Z`,
      dateModified: `${input.updatedAt}T09:00:00Z`,
    },
    files: { files: input.files ?? [] },
    descriptions: { enumFields: DEFAULT_ENUM_FIELDS, enumLookup: {} },
    caseAiAnalysis: null,
  };
}


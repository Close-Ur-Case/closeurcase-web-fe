/** Platform commission rate taken from every lawyer consultation/case
 * settlement — the remainder is credited to the lawyer. */
export const PLATFORM_COMMISSION_RATE = 0.2;

function commissionPayment(input: {
  id: string;
  date: string;
  status: PaymentStatus;
  citizenId: string;
  citizenName: string;
  lawyerId: string;
  lawyerName: string;
  caseId: string;
  caseTitle: string;
  grossAmount: number;
}): Payment {
  const platformAmount = Math.round(input.grossAmount * PLATFORM_COMMISSION_RATE);
  return {
    ...input,
    source: "commission",
    platformAmount,
    lawyerAmount: input.grossAmount - platformAmount,
  };
}

